import { expect, test } from "@playwright/test";

test("Console IDs remain usable through API operations and display-name edits", async ({ page, context }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.goto("/dev/login");
  const project = `identity-${crypto.randomUUID()}`;
  const created = await page.request.post("/api/projects", { data: { project, name: "Identity example" } });
  expect(created.ok(), await created.text()).toBeTruthy();
  const body = await created.json();
  expect(body.project).toBe(project);
  expect(body).not.toHaveProperty("id");
  expect(body).not.toHaveProperty("slug");
  const base = `/api/projects/${project}`;
  const scope = `project=${project}&environment=production`;
  await page.goto(`/settings/project?${scope}`);
  await page.getByRole("button", { name: `Copy ${project}`, exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(project);
  await page.getByLabel("Name", { exact: true }).fill("Renamed project");
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByRole("button", { name: "Save changes" })).toHaveCount(0);
  expect((await (await page.request.get(base)).json()).project).toBe(project);
  expect((await page.request.patch(base, { data: { name: "Renamed", project: "replacement" } })).status()).toBe(400);
  await page.goto(`/settings/environments?${scope}`);
  const row = page.getByRole("row").filter({ has: page.getByTitle("production", { exact: true }) });
  await row.getByRole("button", { name: /^Actions for / }).click();
  await page.getByRole("menuitem", { name: "Copy ID", exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe("production");
  await row.getByRole("button", { name: /^Actions for / }).click();
  await page.getByRole("menuitem", { name: "Edit", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("Environment ID (not editable)")).toHaveValue("production");
  await dialog.getByLabel("Name", { exact: true }).fill("Live workspace");
  await dialog.getByRole("button", { name: "Save", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect((await page.request.patch(`${base}/environments/production`, { data: { name: "Live", environment: "replacement" } })).status()).toBe(400);
  await page.goto(`/settings/secrets?${scope}`);
  // With no secrets yet, the empty state names the Environment and offers the one action.
  await expect(page.getByText("No secrets in Live workspace yet.", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Set secret in Live workspace", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Set secret", exact: true }).click();
  await page.getByLabel("Secret ID", { exact: true }).fill("GITHUB_TOKEN");
  await page.getByLabel("Value", { exact: true }).fill("synthetic-browser-value");
  await page.getByRole("dialog").getByRole("button", { name: "Save", exact: true }).click();
  await page.getByRole("button", { name: "Actions for GITHUB_TOKEN", exact: true }).click();
  await page.getByRole("menuitem", { name: "Copy ID", exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe("GITHUB_TOKEN");
  const secret = await (await page.request.get(`${base}/environments/production/secrets/GITHUB_TOKEN`)).json();
  expect(secret.secret).toBe("GITHUB_TOKEN");
  expect(secret).not.toHaveProperty("id");
  expect(secret).not.toHaveProperty("name");
  expect(secret).not.toHaveProperty("value");
  expect((await page.request.get(`${base}/environments/staging/secrets/GITHUB_TOKEN`)).status()).toBe(404);
});
