import { build } from "esbuild"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"

const check = process.argv.includes("--check")
const { typescript } = JSON.parse(await readFile("internal/version/runtime-dependencies.json", "utf8"))
const packagePath = "packages/module-execution/package.json"
const pkg = JSON.parse(await readFile(packagePath, "utf8"))
if (pkg.dependencies.typescript !== typescript.version) {
  if (check) throw new Error("Runtime TypeScript package projection is stale; run scripts/build-module-execution-entry.sh")
  pkg.dependencies.typescript = typescript.version
  await writeFile(packagePath, JSON.stringify(pkg, null, 2) + "\n")
}
const versionPath = "packages/module-execution/src/runtime-dependencies.ts"
const versionSource = `// Generated by scripts/build-module-execution-entry.ts; do not edit.\nexport const typescriptVersion = ${JSON.stringify(typescript.version)} as const\n`
if (check) {
  if (await readFile(versionPath, "utf8") !== versionSource) throw new Error("Runtime TypeScript source projection is stale; run scripts/build-module-execution-entry.sh")
} else await writeFile(versionPath, versionSource)
// Keep Bun's native package resolution/integrity contract; authoring and website
// TypeScript dependencies are independent of this Runtime package.
const lock = Bun.JSONC.parse(await readFile("bun.lock", "utf8"))
const locked = lock.packages[`${pkg.name}/typescript`]
if (lock.workspaces["packages/module-execution"].dependencies.typescript !== typescript.version ||
    locked?.[0] !== `typescript@${typescript.version}` || locked?.[3] !== typescript.integrity) {
  throw new Error("Runtime TypeScript lock projection is stale; run bun install --ignore-scripts")
}
const installed = JSON.parse(await readFile("packages/module-execution/node_modules/typescript/package.json", "utf8"))
if (installed.version !== typescript.version) throw new Error("Runtime TypeScript installation is stale; run bun install --frozen-lockfile --ignore-scripts")
const target = resolve("internal/moduleexecution/loader.mjs")
const result = await build({
  entryPoints: ["packages/module-execution/src/index.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  write: false,
  plugins: [{ name: "platform-typescript", setup(build) {
    build.onResolve({ filter: /^typescript$/ }, () => ({ path: "./typescript.cjs", external: true }))
  } }],
})
const bytes = result.outputFiles[0]!.text
await mkdir(dirname(target), { recursive: true })
if (check) {
  if (await readFile(target, "utf8") !== bytes) throw new Error("module execution entry is stale; run scripts/build-module-execution-entry.sh")
} else await writeFile(target, bytes)
// Local execution of embedded platform entries needs the same external API as
// the Nix Runtime/compiler closures. This dependency is not vendored in Git.
const library = resolve("packages/module-execution/node_modules/typescript/lib/typescript.js")
await writeFile(resolve(dirname(target), "typescript.cjs"), await readFile(library))
